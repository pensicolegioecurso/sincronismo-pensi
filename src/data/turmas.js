// Gera o array plano: [{ unidade, serie, turno, turma }, ...]
export const TURMAS = Object.entries(DADOS).flatMap(([unidade, series]) =>
  Object.entries(series).flatMap(([serie, turnos]) =>
    Object.entries(turnos).flatMap(([turno, nomes]) =>
      nomes.map((turma) => ({ unidade, serie, turno, turma }))
    )
  )
);

// Helpers
export function getSeriesPorUnidades(unidadesSelecionadas) {
  if (!unidadesSelecionadas.length) return [];
  const filtradas = TURMAS.filter((t) => unidadesSelecionadas.includes(t.unidade));
  return [...new Set(filtradas.map((t) => t.serie))].sort((a, b) => a.localeCompare(b, "pt-BR"));
}

export function getTurmasPorUnidadesESeries(unidadesSelecionadas, seriesSelecionadas) {
  if (!unidadesSelecionadas.length || !seriesSelecionadas.length) return [];
  return TURMAS.filter(
    (t) => unidadesSelecionadas.includes(t.unidade) && seriesSelecionadas.includes(t.serie)
  );
}